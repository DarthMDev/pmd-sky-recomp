#!/usr/bin/env python3
"""
SkyRecompiled -- PMDSky Symbol Bindings Generator
================================================
Parses pmdsky-debug YAML symbol tables (symbols/{arm9,ram,overlay11,overlay29,overlay00,overlay01}.yml)
and generates a typed C++20 header:
  include/skyrecomp/pmdsky_addrs.hpp

Exposes compile-time guest addresses for core engine globals and functions across
supported regions (NA, EU).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SYMBOLS_DIR = REPO_ROOT / "third_party" / "pmdsky-debug" / "symbols"
DEFAULT_OUT = REPO_ROOT / "include" / "skyrecomp" / "pmdsky_addrs.hpp"

# Core symbols required for native hooks (widescreen, interpolation, online rescue)
TARGET_SYMBOLS = [
    # Boot / crt0
    "_start",
    "NitroMain",
    "MIi_UncompressBackward",
    "do_autoload",
    # Dungeon Engine (overlay 29)
    "RunDungeon",
    "GetWeatherColorTable",
    "DUNGEON_PTR_MASTER",
    "DUNGEON_PTR",
    "TOP_SCREEN_STATUS_PTR",
    # Ground Engine (overlay 11)
    "GROUND_STATE_PTRS",
    # Game State & Ram Globals
    "GAME_STATE_VALUES",
    "BAG_ITEMS_PTR_MIRROR",
    # Wonder Mail S & Rescue Tables
    "WONDER_MAIL_BITS_MAP",
    "WONDER_MAIL_BITS_SWAP",
]


def parse_symbols_from_yaml(yaml_path: Path) -> dict[str, dict[str, int]]:
    """Zero-dependency parser for pmdsky-debug resymgen YAML files."""
    if not yaml_path.exists():
        return {}

    lines = yaml_path.read_text(encoding="utf-8").splitlines()
    symbols: dict[str, dict[str, int]] = {}

    cur_name: str | None = None
    in_address_block = False

    for line in lines:
        stripped = line.strip()
        indent = len(line) - len(line.lstrip())

        # Check for symbol name: `- name: FooBar`
        m_name = re.match(r"^-\s+name:\s+([A-Za-z0-9_]+)", stripped)
        if m_name:
            cur_name = m_name.group(1)
            in_address_block = False
            continue

        if cur_name is None:
            continue

        # Check for address block header
        if stripped == "address:":
            in_address_block = True
            if cur_name not in symbols:
                symbols[cur_name] = {}
            continue

        # If we hit another property (length, description, type, etc.), exit address block
        if stripped.endswith(":") and stripped != "address:":
            in_address_block = False

        # Inside address block: `NA: 0x2000800`
        if in_address_block:
            m_addr = re.match(r"^([A-Z0-9_-]+):\s*(0x[0-9A-Fa-f]+|\d+)", stripped)
            if m_addr:
                region_tag = m_addr.group(1)
                val_str = m_addr.group(2)
                addr_val = int(val_str, 16) if val_str.startswith("0x") else int(val_str)
                symbols[cur_name][region_tag] = addr_val
            elif indent <= 4 and not stripped.startswith("-") and stripped != "":
                in_address_block = False

    return symbols


def generate_cpp_header(symbols_map: dict[str, dict[str, int]], out_path: Path) -> None:
    lines = [
        "// AUTO-GENERATED by translator/gen_pmdsky_bindings.py -- DO NOT EDIT",
        "// Symbols sourced from https://github.com/UsernameFodder/pmdsky-debug",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace skyrecomp::pmdsky {",
        "",
        "enum class Region : uint8_t {",
        "    NA,",
        "    EU,",
        "};",
        "",
        "struct SymbolAddresses {",
    ]

    for sym in TARGET_SYMBOLS:
        lines.append(f"    uint32_t {sym};")

    lines.extend([
        "};",
        "",
    ])

    for region in ["NA", "EU"]:
        lines.append(f"inline constexpr SymbolAddresses {region} = {{")
        for sym in TARGET_SYMBOLS:
            addrs = symbols_map.get(sym, {})
            addr_val = addrs.get(region, 0)
            lines.append(f"    .{sym} = 0x{addr_val:08X},")
        lines.append("};")
        lines.append("")

    lines.extend([
        "[[nodiscard]] inline constexpr const SymbolAddresses& Get(Region r) noexcept {",
        "    return (r == Region::EU) ? EU : NA;",
        "}",
        "",
        "} // namespace skyrecomp::pmdsky",
        "",
    ])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[gen_pmdsky_bindings] Wrote {len(TARGET_SYMBOLS)} symbols to {out_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description="PMDSky C++ Symbol Bindings Generator")
    parser.add_argument("--symbols-dir", type=Path, default=SYMBOLS_DIR, help="Path to pmdsky-debug symbols dir")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Output C++ header path")
    args = parser.parse_args()

    yaml_files = [
        args.symbols_dir / "arm9.yml",
        args.symbols_dir / "ram.yml",
        args.symbols_dir / "overlay11.yml",
        args.symbols_dir / "overlay29.yml",
        args.symbols_dir / "overlay00.yml",
        args.symbols_dir / "overlay01.yml",
    ]

    merged_symbols: dict[str, dict[str, int]] = {}
    for yf in yaml_files:
        if yf.exists():
            s = parse_symbols_from_yaml(yf)
            for k, v in s.items():
                if k not in merged_symbols:
                    merged_symbols[k] = {}
                merged_symbols[k].update(v)

    generate_cpp_header(merged_symbols, args.out)


if __name__ == "__main__":
    main()
